//  Write a program to print "MySirG" 5 times on the screen.

/*
Program Title : Print "MySirG" Five Times

Description :
This program uses a loop to print the string "MySirG" five times on the screen.
A for loop is used to repeat the printing statement exactly five times.

Input :
- No input required

Processing :
- Initialize a loop counter
- Repeat the loop five times
- Print "MySirG" in each iteration

Output :
- Display the text "MySirG" five times on the screen
*/

#include <stdio.h>

int main () {
    // Print MySirG 5 time on the screen
    for (int i = 1; i <= 5; i++)
    {
        printf("MySirG\n");
    }
    
    return 0;
}